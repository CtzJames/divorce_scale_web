function normalizeNarcissismRiskReportLevel(level) {
  if (level === "medium") return "moderate";
  if (NARCISSISM_RISK_REPORT_LEVEL_ORDER.includes(level)) return level;
  return null;
}

export function getNarcissismRiskOverallCopy(level) {
  const normalizedLevel = normalizeNarcissismRiskReportLevel(level);
  return normalizedLevel ? overallLevels[normalizedLevel] ?? null : null;
}

export function getNarcissismRiskDimensionCopy(dimensionCode, level) {
  const dimensionCopy = narcissismRiskDimensions[dimensionCode];
  if (!dimensionCopy) return null;

  if (level === undefined || level === null) {
    return dimensionCopy;
  }

  const normalizedLevel = normalizeNarcissismRiskReportLevel(level);
  if (!normalizedLevel) return null;

  return dimensionCopy.levels[normalizedLevel] ?? null;
}

export function getNarcissismRiskTriggerCopy(questionNoOrId) {
  if (questionNoOrId === undefined || questionNoOrId === null) return null;

  const normalizedKey =
    typeof questionNoOrId === "number"
      ? `Q${questionNoOrId}`
      : String(questionNoOrId).trim();

  if (highRiskTriggers[normalizedKey]) return highRiskTriggers[normalizedKey];

  return (
    Object.values(highRiskTriggers).find(
      (item) =>
        item.questionId === normalizedKey ||
        `Q${item.questionNo}` === normalizedKey
    ) ?? null
  );
}

