export function normalizeReportLevel(level) {
  if (level === "medium") return "mid";
  if (level === "high" || level === "mid" || level === "low") return level;
  return "mid";
}

export function getReportScoreBand(avg) {
  if (!Number.isFinite(avg)) return "mid";
  if (avg < 3) return "low";
  if (avg < 4) return "mid";
  return "high";
}

export function getTotalResultCopy({ resultLevel, crossBorder }) {
  const levelKey = normalizeReportLevel(resultLevel);
  return TOTAL_RESULT_COPY[crossBorder ? "crossBorder" : "standard"][levelKey];
}

export function getIncludedDimensionCodes({ childGateAnswer, crossBorderGateAnswer }) {
  return REPORT_DIMENSION_ORDER.filter((code) => {
    if (code === "D3" && !(childGateAnswer === true || childGateAnswer === "yes")) {
      return false;
    }

    if (
      code === "D7" &&
      !(crossBorderGateAnswer === true || crossBorderGateAnswer === "yes")
    ) {
      return false;
    }

    return true;
  });
}
